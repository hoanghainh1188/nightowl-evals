import type { FailureToExport } from '../storage/failures.js';
import { evalId } from './eval-case.js';
import { PROMPTFOO_MARKER } from './formats.js';

function yamlEscapeDouble(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
}

function yamlLiteralBlock(value: string, indent: number): string {
  const pad = ' '.repeat(indent);
  const body = value.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = body.split('\n');
  // chomp: keep final newline semantics via |-
  return `|\n${lines.map((line) => `${pad}${line}`).join('\n')}`;
}

/**
 * Emit a minimal Promptfoo config YAML. Providers default to `echo` — replace with a real model before running.
 */
export function toPromptfooYaml(
  failures: ReadonlyArray<{ readonly failure: FailureToExport; readonly fileBefore: string | null }>,
): string {
  const chunks: string[] = [
    PROMPTFOO_MARKER,
    '# Generated by nightowl export --format promptfoo. Replace providers before running promptfoo.',
    'prompts:',
    '  - |-',
    '    You are fixing a recorded AI coding failure.',
    '    File: {{file_path}}',
    '    {% if prompt %}Prompt: {{prompt}}{% endif %}',
    '    File before the bad edit:',
    '    ```',
    '    {{file_before}}',
    '    ```',
    '    Defective AI output (do not repeat):',
    '    ```',
    '    {{rejected}}',
    '    ```',
    '    Return only the corrected file contents.',
    '',
    'providers:',
    "  - echo  # replace with e.g. openai:gpt-4o or anthropic:messages:claude-sonnet-4-5",
    '',
    'tests:',
  ];

  for (const { failure, fileBefore } of failures) {
    const id = evalId(failure);
    chunks.push(`  - description: ${yamlEscapeDouble(id)}`);
    chunks.push('    vars:');
    chunks.push(`      file_path: ${yamlEscapeDouble(failure.filePath)}`);
    chunks.push(`      prompt: ${yamlEscapeDouble(failure.prompt ?? '')}`);
    chunks.push(`      file_before: ${yamlLiteralBlock(fileBefore ?? '', 8)}`);
    chunks.push(`      rejected: ${yamlLiteralBlock(failure.aiContent, 8)}`);
    chunks.push('    assert:');
    chunks.push('      - type: equals');
    chunks.push(`        value: ${yamlLiteralBlock(failure.finalContent, 10)}`);
  }

  if (failures.length === 0) {
    chunks.push('  []');
  }

  return `${chunks.join('\n')}\n`;
}
