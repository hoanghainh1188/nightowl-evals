#!/usr/bin/env node
/**
 * Format a nightowl report JSON file into a sticky PR comment body.
 * CLI: node format-report.mjs <report.json>
 */

import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export const STICKY_MARKER = '<!-- nightowl-evals-report -->';

function percent(rate) {
  if (rate === null || rate === undefined) return 'n/a';
  return `${Math.round(Number(rate) * 100)}%`;
}

function topEntries(record, limit = 5) {
  if (!record || typeof record !== 'object') return [];
  return Object.entries(record)
    .map(([key, value]) => [key, Number(value) || 0])
    .filter(([, n]) => n > 0)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit);
}

function topModules(modules, limit = 5) {
  if (!Array.isArray(modules)) return [];
  return modules
    .map((m) => [String(m.module ?? ''), Number(m.failures) || 0])
    .filter(([name, n]) => name && n > 0)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit);
}

function bulletList(entries) {
  if (entries.length === 0) return '_None_';
  return entries.map(([label, n]) => `- **${label}**: ${n}`).join('\n');
}

/**
 * @param {Record<string, unknown>} report
 * @returns {string}
 */
export function formatReportMarkdown(report) {
  const total = Number(report.total) || 0;
  const changed = report.changed_rate ?? {};
  const failures = Number(changed.failures) || 0;
  const checked = Number(changed.checked) || 0;
  const rateLabel = percent(changed.rate ?? null);
  const since = report.since ? String(report.since).slice(0, 10) : null;

  const lines = [
    STICKY_MARKER,
    '## AI Coding Health Report',
    '',
    since ? `_Window since ${since}_` : '_All recorded history_',
    '',
    '| Metric | Value |',
    '| --- | --- |',
    `| Total failures | ${total} |`,
    `| AI edits changed | ${rateLabel} (${failures} of ${checked} checked) |`,
    `| Unclassified | ${Number(report.unclassified) || 0} |`,
    `| Dismissed (not counted) | ${Number(report.dismissed) || 0} |`,
    '',
    '### Top categories',
    bulletList(topEntries(report.by_category)),
    '',
    '### Top modules',
    bulletList(topModules(report.by_module)),
    '',
    '_Generated by [NightOwl Evals](https://github.com/hoanghainh1188/nightowl-evals) quality gate._',
    '',
  ];
  return lines.join('\n');
}

async function main(reportPath) {
  const raw = await readFile(reportPath, 'utf8');
  const report = JSON.parse(raw);
  process.stdout.write(formatReportMarkdown(report));
}

const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  const reportPath = process.argv[2];
  if (!reportPath) {
    process.stderr.write('usage: node format-report.mjs <report.json>\n');
    process.exit(1);
  }
  main(reportPath).catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  });
}
